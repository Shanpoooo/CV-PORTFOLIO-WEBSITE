const langDropdown = document.getElementById("lang-dropdown");
const langSummary = document.getElementById("lang-summary");
const langButtons = document.querySelectorAll("[data-set-lang]");
let currentLang = localStorage.getItem("siteLang") || "en";

function applyLanguage(lang) {
  document.querySelectorAll("[data-lang]").forEach((el) => {
    const key = el.dataset.lang;
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  if (langSummary) {
    langSummary.textContent = `[LANG: ${lang.toUpperCase()} ▾]`;
  }
  document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  localStorage.setItem("siteLang", lang);
}

langButtons.forEach((btn) => {
  btn.addEventListener("click", () => {
    currentLang = btn.dataset.setLang;
    applyLanguage(currentLang);
    if (langDropdown) langDropdown.removeAttribute("open");
  });
});

document.addEventListener("click", (e) => {
  if (langDropdown && !langDropdown.contains(e.target)) {
    langDropdown.removeAttribute("open");
  }
});

applyLanguage(currentLang);